"""v49.19: the profile header's cartoon San Antonio skyline (Tower of the Americas and friends), reused from the app's own
header art (index.html's HEADER-ART <g class="sky-sa">, generated by tools/make_header_art.py). Writes
static/site/sa-skyline.svg in the app's light-theme skyline colors as-is (style.css .skyline fill #000, .sky-win the turquoise
at .5): a black silhouette for the turquoise sky (no yellow). Rerun after the header art changes."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / "static" / "index.html").read_text(encoding="utf-8")
g = re.search(r'<g class="sky-sa">(.*?)</g>', html, re.S).group(1)
g = g.replace('class="sky-win"', 'fill="#00C9CD" fill-opacity=".5"')
svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="300 58 800 82" preserveAspectRatio="xMidYMax slice" aria-hidden="true">'
       f'<g fill="#000">{g}</g></svg>\n')
# viewBox: cropped to the buildings (tops start at y≈64) and centred near the Tower of the Americas (x≈648), so the
# header's bigger band (v49.19.1) shows tall buildings instead of empty sky; wider screens see more of the city.
(ROOT / "static" / "site" / "sa-skyline.svg").write_text(svg, encoding="utf-8")
print("wrote static/site/sa-skyline.svg", len(svg))
