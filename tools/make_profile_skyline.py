"""v49.19: the profile header's cartoon San Antonio skyline (Tower of the Americas and friends), reused from the app's own
header art (index.html's HEADER-ART <g class="sky-sa">, generated by tools/make_header_art.py). Writes
static/site/sa-skyline.svg: black buildings with silver windows (Fiesta palette, no yellow). Rerun after the header art changes."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / "static" / "index.html").read_text(encoding="utf-8")
g = re.search(r'<g class="sky-sa">(.*?)</g>', html, re.S).group(1)
g = g.replace('class="sky-win"', 'fill="#C0C0C0"')
svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 140" preserveAspectRatio="xMidYMax slice" aria-hidden="true">'
       f'<g fill="#000">{g}</g></svg>\n')
(ROOT / "static" / "site" / "sa-skyline.svg").write_text(svg, encoding="utf-8")
print("wrote static/site/sa-skyline.svg", len(svg))
